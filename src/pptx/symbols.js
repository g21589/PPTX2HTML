const TABLES = {
  wingdings: WINGDINGS,
  'wingdings 2': WINGDINGS2,
  'wingdings 3': WINGDINGS3,
  webdings: WEBDINGS,
  symbol: SYMBOL,
  'monotype sorts': WINGDINGS,
  'zapfdingbats': WINGDINGS,
};

export function isSymbolFont(font) {
  return !!(font && TABLES[String(font).toLowerCase()]);
}

/** Map text written in a symbol font to Unicode. Unknown characters are kept. */
export function mapSymbolText(text, font) {
  const table = TABLES[String(font || '').toLowerCase()];
  if (!table || !text) return text;
  let out = '';
  for (const ch of text) {
    let code = ch.codePointAt(0);
    if (code >= 0xf000 && code <= 0xf0ff) code -= 0xf000;
    const m = table[code];
    if (m) out += String.fromCodePoint(m);
    else if (code >= 0x20 && code < 0x7f && table === SYMBOL) out += String.fromCharCode(code);
    else out += ch;
  }
  return out;
}
