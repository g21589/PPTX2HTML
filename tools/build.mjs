#!/usr/bin/env node
/**
 * Build script:
 *  - src/generated/player-source.js : minified runtime player embedded in generated HTML
 *  - dist/pptx2html.js       : ES module bundle of the converter (browser)
 *  - dist/pptx2html.min.js   : IIFE bundle exposing the global PPTX2HTML
 *  - dist/pptx2html-player.js: standalone runtime player
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const player = await esbuild.build({
  entryPoints: [path.join(root, 'src/runtime/standalone.js')],
  bundle: true, minify: true, format: 'iife', target: ['es2019'], write: false, legalComments: 'none',
});
const code = player.outputFiles[0].text.trim();
const mod = `// Generated by tools/build.mjs - do not edit.\n// Minified build of src/runtime (the presentation player embedded in converted documents).\nexport const PLAYER_SOURCE = ${JSON.stringify(code)};\n`;
const target = path.join(root, 'src/generated/player-source.js');
if (check) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (cur !== mod) {
    console.error('src/generated/player-source.js is out of date: run `npm run build`');
    process.exit(1);
  }
  console.log('player source up to date');
  process.exit(0);
}
fs.writeFileSync(target, mod);
console.log('player:', (code.length / 1024).toFixed(1), 'KiB');

fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
await esbuild.build({ entryPoints: [path.join(root, 'src/index.js')], bundle: true, format: 'esm', target: ['es2019'], outfile: path.join(root, 'dist/pptx2html.js'), legalComments: 'none' });
await esbuild.build({ entryPoints: [path.join(root, 'src/index.js')], bundle: true, minify: true, format: 'iife', globalName: 'PPTX2HTML', target: ['es2019'], outfile: path.join(root, 'dist/pptx2html.min.js'), legalComments: 'none' });
fs.writeFileSync(path.join(root, 'dist/pptx2html-player.js'), code + '\n');
for (const f of ['pptx2html.js', 'pptx2html.min.js', 'pptx2html-player.js']) {
  console.log('dist/' + f, (fs.statSync(path.join(root, 'dist', f)).size / 1024).toFixed(1), 'KiB');
}
