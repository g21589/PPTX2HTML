#!/usr/bin/env node
/**
 * Compiles the ECMA-376 preset geometry definitions:
 *  - presetShapeDefinitions.xml    -> src/geometry/presets.js
 *  - presetTextWarpDefinitions.xml -> src/geometry/textwarps.js
 *
 * Usage: node tools/build-presets.mjs [shapes.xml] [textwarps.xml]
 * Missing files are downloaded (Apache POI and LibreOffice ship copies of
 * the definitions that are part of the ECMA-376 / ISO/IEC 29500 standard).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseXml } from '../src/util/xml.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const SHAPES_URL = 'https://raw.githubusercontent.com/apache/poi/trunk/poi/src/main/resources/org/apache/poi/sl/draw/geom/presetShapeDefinitions.xml';
const WARPS_URL = 'https://raw.githubusercontent.com/LibreOffice/core/master/oox/source/export/presetTextWarpDefinitions.xml';

async function source(file, url) {
  if (file) return fs.readFileSync(file, 'utf8');
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.text();
}

function compile(xml) {
  const root = parseXml(xml);
  const out = {};
  for (const shape of root.children) {
    const def = {};
    const av = shape.child('a:avLst');
    if (av && av.children.length) def.av = av.children.map((g) => g.attrs.name + ' ' + g.attrs.fmla).join(';');
    const gd = shape.child('a:gdLst');
    if (gd && gd.children.length) def.gd = gd.children.map((g) => g.attrs.name + ' ' + g.attrs.fmla).join(';');
    const rect = shape.child('a:rect');
    if (rect) def.rect = [rect.attrs.l, rect.attrs.t, rect.attrs.r, rect.attrs.b].join(' ');
    const cx = shape.child('a:cxnLst');
    if (cx && cx.children.length) {
      def.cxn = cx.children.map((c) => { const p = c.child('a:pos'); return [c.attrs.ang, p.attrs.x, p.attrs.y].join(' '); }).join(';');
    }
    const pl = shape.child('a:pathLst');
    def.path = [];
    for (const p of pl ? pl.all('a:path') : []) {
      const head = [p.attrs.w || '0', p.attrs.h || '0', p.attrs.fill || 'norm', p.attrs.stroke === 'false' || p.attrs.stroke === '0' ? '0' : '1', p.attrs.extrusionOk === 'false' || p.attrs.extrusionOk === '0' ? '0' : '1'].join(' ');
      const cmds = [head];
      for (const c of p.children) {
        const pts = c.all('a:pt').map((pt) => pt.attrs.x + ' ' + pt.attrs.y).join(' ');
        switch (c.local) {
          case 'moveTo': cmds.push('M ' + pts); break;
          case 'lnTo': cmds.push('L ' + pts); break;
          case 'cubicBezTo': cmds.push('C ' + pts); break;
          case 'quadBezTo': cmds.push('Q ' + pts); break;
          case 'arcTo': cmds.push(['A', c.attrs.wR, c.attrs.hR, c.attrs.stAng, c.attrs.swAng].join(' ')); break;
          case 'close': cmds.push('Z'); break;
          default: throw new Error('unknown path command ' + c.name);
        }
      }
      def.path.push(cmds.join('|'));
    }
    out[shape.name] = def;
  }
  return out;
}

function write(file, comment, name, out) {
  const banner = `// Generated by tools/build-presets.mjs - do not edit.\n// ${comment}\n`;
  const code = `export const ${name} = ` + JSON.stringify(out) + ';\n';
  fs.writeFileSync(path.join(here, '../src/geometry', file), banner + code);
  console.log('wrote', file, Object.keys(out).length, 'definitions,', (code.length / 1024).toFixed(0), 'KiB');
}

write('presets.js', 'Preset shape geometries from ECMA-376 Part 1 (presetShapeDefinitions.xml).', 'PRESETS', compile(await source(process.argv[2], SHAPES_URL)));
write('textwarps.js', 'Preset text warps from ECMA-376 Part 1 (presetTextWarpDefinitions.xml).', 'TEXT_WARPS', compile(await source(process.argv[3], WARPS_URL)));
